#!/usr/bin/env python3
"""Convert fonts.h (made by gen_fonts.py) into the web page's fonts.js, so the page draws text with
exactly the same glyphs as the ESP32 sketch.

Usage: python3 tools/fonts_to_js.py fonts.h > path/to/web/fonts.js
"""
import base64
import re
import sys

src = open(sys.argv[1], encoding="utf-8").read()

fonts = []
for m in re.finditer(r"\{(font\d+)_bitmap, \1_glyphs, (\d+), (\d+), \"([^\"]+)\"\}", src):
    name, count, yadv, label = m.group(1), int(m.group(2)), int(m.group(3)), m.group(4)
    bm = re.search(rf"static const uint8_t {name}_bitmap\[\] = \{{(.*?)\}};", src, re.S).group(1)
    bitmap = bytes(int(x, 16) for x in re.findall(r"0x([0-9A-F]{2})", bm))
    gl = re.search(rf"static const TagGlyph {name}_glyphs\[\] = \{{(.*?)\n\}};", src, re.S).group(1)
    glyphs = [int(x) for g in re.findall(r"\{(-?\d+, -?\d+, -?\d+, -?\d+, -?\d+, -?\d+)\}", gl)
              for x in g.split(", ")]
    assert len(glyphs) == count * 6, name
    fonts.append((label, yadv, bitmap, glyphs))

extra = re.search(r'EXTRA = "([^"]+)"', open(sys.argv[1].replace("fonts.h", "tools/gen_fonts.py"),
                                               encoding="utf-8").read()).group(1)

out = ["// Generated by ESP32_ATC_OEPL_Bridge/tools/fonts_to_js.py from fonts.h (GNU FreeFont, GPLv3 with",
       "// font exception). Do not edit. Same glyphs as the ESP32 sketch.",
       "const b64 = (s) => Uint8Array.from(atob(s), (c) => c.charCodeAt(0));",
       f"export const EXTRA_CHARS = {extra!r};",
       "// glyphs: flat [offset, width, height, xAdvance, xOffset, yOffset] per char from U+0020",
       "export const FONTS = ["]
for label, yadv, bitmap, glyphs in fonts:
    out.append(f"  {{ label: {label!r}, yAdvance: {yadv}, glyphs: Int32Array.from({glyphs}),")
    out.append(f"    bitmap: b64('{base64.b64encode(bitmap).decode()}') }},")
out.append("];")
print("\n".join(out))
