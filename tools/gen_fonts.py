#!/usr/bin/env python3
"""Generate fonts.h for ESP32_ATC_OEPL_Bridge from GNU FreeFont (the typeface behind Adafruit's
FreeSans*.h), adding Romanian diacritics, ° and €.

Sizes are in points at 141 dpi, the same as Adafruit's fontconvert, so {3} (Bold 12 pt) matches
the FreeSansBold12pt7b look exactly. Glyphs are rendered 1-bit (no anti-aliasing), packed MSB-first
row by row, continuous across rows, like GFXfont, but with 32-bit offsets so big sizes fit.

Usage: python3 tools/gen_fonts.py > fonts.h   (needs Pillow; fonts from apt package fonts-freefont-ttf)
"""
from PIL import Image, ImageDraw, ImageFont

FONT_DIR = "/usr/share/fonts/truetype/freefont/"
DPI = 141

# (spec digit, file, points, label)
FONTS = [
    (1, "FreeSans.ttf", 7, "Sans 7pt"),
    (2, "FreeSans.ttf", 9, "Sans 9pt"),
    (3, "FreeSansBold.ttf", 12, "Sans Bold 12pt"),
    (4, "FreeSansBold.ttf", 18, "Sans Bold 18pt"),
    (5, "FreeSansBold.ttf", 24, "Sans Bold 24pt"),
    (6, "FreeSansBold.ttf", 32, "Sans Bold 32pt"),
    (7, "FreeSansBold.ttf", 40, "Sans Bold 40pt"),
    (8, "FreeSansBold.ttf", 52, "Sans Bold 52pt"),
    (9, "FreeSansBold.ttf", 64, "Sans Bold 64pt"),
]

# Code 0x20..0x7E is ASCII; extra glyphs follow from 0x7F in this order. The sketch's UTF-8
# decoder must use the same table (see EXTRA_CHARS there).
EXTRA = "ĂăÂâÎîȘșȚț°€℃"
CHARS = [chr(c) for c in range(0x20, 0x7F)] + list(EXTRA)


def render(path, pt):
    font = ImageFont.truetype(path, size=pt * DPI / 72)
    ascent, descent = font.getmetrics()
    glyphs, bitmap = [], bytearray()
    for ch in CHARS:
        adv = round(font.getlength(ch, mode="1"))
        # Render around a known origin, then crop to the ink (PIL's getbbox starts at the pen).
        pad = int(pt * DPI / 72) + 8
        canvas = Image.new("1", (pad * 3, pad * 3), 0)
        d = ImageDraw.Draw(canvas)
        d.fontmode = "1"
        d.text((pad, pad * 2), ch, font=font, fill=1, anchor="ls")
        box = canvas.getbbox()
        off = len(bitmap)
        if box:
            x0, y0, x1, y1 = box
            w, h = x1 - x0, y1 - y0
            img = canvas.crop(box)
            px = img.load()
            acc = nbits = 0
            for y in range(h):
                for x in range(w):
                    acc = (acc << 1) | (1 if px[x, y] else 0)
                    nbits += 1
                    if nbits == 8:
                        bitmap.append(acc)
                        acc = nbits = 0
            if nbits:
                bitmap.append(acc << (8 - nbits))
            x0 -= pad
            y0 -= pad * 2
        else:
            w = h = x0 = y0 = 0
        glyphs.append((off, w, h, adv, x0, y0))
    return glyphs, bitmap, ascent + descent


def main():
    out = ["// Generated by tools/gen_fonts.py from GNU FreeFont (GPLv3 with font exception). Do not edit.",
           "#pragma once", "#include <stdint.h>", "",
           "struct TagGlyph { uint32_t offset; uint8_t width, height, xAdvance; int8_t xOffset; int16_t yOffset; };",
           "struct TagFont { const uint8_t *bitmap; const TagGlyph *glyphs; uint16_t count; uint16_t yAdvance; const char *label; };",
           ""]
    names = []
    for digit, file, pt, label in FONTS:
        glyphs, bitmap, yadv = render(FONT_DIR + file, pt)
        name = f"font{digit}"
        names.append((name, len(glyphs), yadv, label))
        out.append(f"// {label}: {len(bitmap)} bytes")
        out.append(f"static const uint8_t {name}_bitmap[] = {{")
        for i in range(0, len(bitmap), 24):
            out.append("  " + ",".join(f"0x{b:02X}" for b in bitmap[i:i + 24]) + ",")
        out.append("};")
        out.append(f"static const TagGlyph {name}_glyphs[] = {{")
        for (off, w, h, adv, xo, yo), ch in zip(glyphs, CHARS):
            assert w < 256 and h < 256 and adv < 256 and -128 <= xo < 128
            out.append(f"  {{{off}, {w}, {h}, {adv}, {xo}, {yo}}},  // U+{ord(ch):04X}")
        out.append("};")
        out.append("")
    out.append("static const TagFont kFonts[] = {")
    for name, count, yadv, label in names:
        out.append(f'  {{{name}_bitmap, {name}_glyphs, {count}, {yadv}, "{label}"}},')
    out.append("};")
    out.append(f"static const int kFontCount = {len(names)};")
    print("\n".join(out))


if __name__ == "__main__":
    main()
